"""Gate 2: does one full-length conversation fit on one 80 GB card with activations captured?

Defined in PREREGISTRATION.md section 5.2. Run on the GPU instance:

    python src/gate2_memory.py

"Full-length" is the worst case the study can produce: every assistant turn is forced to the
maximum number of new tokens, and the user turns are long. The user turns here are filler
written for this test. Nothing generated by this script is study data, and no projection is
computed from it.

Layer convention: layer L is the output of transformer block L (zero-indexed), which is how the
released axis and role vectors are indexed.
"""

from __future__ import annotations

import json
import os
import sys
import time
import tomllib
from pathlib import Path

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer, __version__ as transformers_version

REPO_ROOT = Path(__file__).resolve().parent.parent
RESULT_PATH = REPO_ROOT / "results" / "gate2_memory.json"

SYSTEM_PROMPT = "You are a helpful assistant."
FILLER_TOPICS = [
    "planning a week of meals for a household of four on a fixed budget",
    "choosing between two laptops for writing and light photo editing",
    "organising a shared folder of documents so that files are easy to find",
    "preparing a ten-minute talk for colleagues about a project that went well",
    "setting up a simple routine for backing up family photographs",
]


def user_turn(i: int) -> str:
    """A long filler user message, about 150 tokens."""
    topic = FILLER_TOPICS[i % len(FILLER_TOPICS)]
    return (
        f"Thanks, that helps. Next question, number {i + 1}. I am {topic}, and I would like you "
        "to go through it carefully with me. Please set out the main options, say what each one "
        "costs in time and effort, point out anything people commonly get wrong, and finish with "
        "a short recommendation. I have about an hour this evening to work on it and I would "
        "like to end up with a clear list of steps that I can follow without having to come "
        "back and ask again. If there is something you would need to know about my situation "
        "before you could answer well, say what it is and make a reasonable assumption so that "
        "you can still give me a complete answer now."
    )


def gb(n_bytes: int) -> float:
    return round(n_bytes / 2**30, 2)


def render(tok, messages, add_generation_prompt: bool) -> list[int]:
    out = tok.apply_chat_template(
        messages, tokenize=True, add_generation_prompt=add_generation_prompt, enable_thinking=False
    )
    return list(out["input_ids"] if hasattr(out, "keys") else out)


def response_spans(tok, messages) -> tuple[list[int], list[tuple[int, int]]]:
    """Token ids of the whole conversation and the [start, end) span of each assistant reply.

    A span covers the reply's own tokens: the role header before it and the end-of-turn marker
    after it are left out.
    """
    full = render(tok, messages, add_generation_prompt=False)
    spans = []
    for i, m in enumerate(messages):
        if m["role"] != "assistant":
            continue
        a = len(render(tok, messages[:i], add_generation_prompt=False))
        b = len(render(tok, messages[: i + 1], add_generation_prompt=False))
        content = tok(m["content"], add_special_tokens=False)["input_ids"]
        block = full[a:b]
        start = next(
            (h for h in range(len(block) - len(content) + 1) if block[h : h + len(content)] == content),
            None,
        )
        if start is None:
            raise ValueError(f"could not locate the reply of message {i} in the rendered conversation")
        spans.append((a + start, a + start + len(content)))
    return full, spans


def main() -> None:
    with open(REPO_ROOT / "configs" / "study.toml", "rb") as f:
        cfg = tomllib.load(f)
    name = cfg["model"]["name"]
    layers = sorted([cfg["projection"]["target_layer"], *cfg["projection"]["reliability_layers"]])
    n_turns = cfg["sample"]["assistant_turns"]
    gen = cfg["generation"]
    floor = cfg["gate2"]["min_assistant_turns"]

    torch.manual_seed(cfg["seeds"]["generation"])
    tok = AutoTokenizer.from_pretrained(name)
    t0 = time.time()
    model = AutoModelForCausalLM.from_pretrained(name, torch_dtype=torch.bfloat16, device_map={"": 0})
    model.eval()
    load_seconds = round(time.time() - t0)
    after_load = torch.cuda.memory_allocated()
    blocks = model.model.layers
    assert len(blocks) == cfg["model"]["total_layers"]

    # 1. Generate, every assistant turn forced to full length.
    messages = [{"role": "system", "content": SYSTEM_PROMPT}]
    torch.cuda.reset_peak_memory_stats()
    generated, error = 0, None
    t0 = time.time()
    for i in range(n_turns):
        messages.append({"role": "user", "content": user_turn(i)})
        ids = torch.tensor([render(tok, messages, add_generation_prompt=True)], device=model.device)
        try:
            with torch.no_grad():
                out = model.generate(
                    ids,
                    attention_mask=torch.ones_like(ids),
                    do_sample=True,
                    temperature=gen["temperature"],
                    top_p=gen["top_p"],
                    max_new_tokens=gen["max_new_tokens"],
                    min_new_tokens=gen["max_new_tokens"],
                )
        except torch.cuda.OutOfMemoryError as e:
            error = f"generation, turn {i + 1}: {str(e)[:200]}"
            messages.pop()
            torch.cuda.empty_cache()
            break
        messages.append({"role": "assistant", "content": tok.decode(out[0, ids.shape[1] :], skip_special_tokens=True)})
        generated += 1
        print(f"turn {i + 1}: context {out.shape[1]} tokens, peak {gb(torch.cuda.max_memory_allocated())} GB", flush=True)
    generation_seconds = round(time.time() - t0)
    peak_generation = torch.cuda.max_memory_allocated()

    # 2. Capture: one forward pass over the whole conversation with hooks on the study's layers.
    captured, span_lengths, context_tokens, peak_capture = 0, [], 0, 0
    turns = generated
    while turns >= 1:
        convo = messages[: 1 + 2 * turns]
        full, spans = response_spans(tok, convo)
        store: dict[int, torch.Tensor] = {}
        handles = [
            blocks[layer].register_forward_hook(
                lambda _m, _i, o, layer=layer: store.__setitem__(layer, (o[0] if isinstance(o, tuple) else o)[0])
            )
            for layer in layers
        ]
        torch.cuda.empty_cache()
        torch.cuda.reset_peak_memory_stats()
        try:
            with torch.no_grad():
                model(torch.tensor([full], device=model.device))
            means = torch.stack(
                [torch.stack([store[layer][a:b].float().mean(dim=0) for layer in layers]) for a, b in spans]
            )
            assert means.shape == (turns, len(layers), cfg["model"]["hidden_size"])
            assert torch.isfinite(means).all()
            captured, span_lengths, context_tokens = turns, [b - a for a, b in spans], len(full)
            peak_capture = torch.cuda.max_memory_allocated()
            break
        except torch.cuda.OutOfMemoryError as e:
            error = error or f"capture, {turns} turns: {str(e)[:200]}"
            turns -= 1
        finally:
            for h in handles:
                h.remove()
            store.clear()

    props = torch.cuda.get_device_properties(0)
    result = {
        "gate": "2: one full-length conversation with activations captured, one card",
        "git_commit": os.environ.get("STUDY_COMMIT", "unknown"),
        "model": name,
        "thinking_mode": False,
        "gpu": props.name,
        "gpu_memory_gb": gb(props.total_memory),
        "torch": torch.__version__,
        "transformers": transformers_version,
        "dtype": "bfloat16",
        "layers_captured": layers,
        "max_new_tokens_per_turn_forced": gen["max_new_tokens"],
        "assistant_turns_target": n_turns,
        "assistant_turns_generated": generated,
        "assistant_turns_captured": captured,
        "context_tokens_at_capture": context_tokens,
        "reply_span_tokens": span_lengths,
        "memory_after_load_gb": gb(after_load),
        "peak_memory_generation_gb": gb(peak_generation),
        "peak_memory_capture_gb": gb(peak_capture),
        "load_seconds": load_seconds,
        "generation_seconds": generation_seconds,
        "out_of_memory": error,
        "turn_count_supported": captured,
        "passed": bool(captured >= n_turns),
        "below_floor": bool(captured < floor),
    }
    RESULT_PATH.parent.mkdir(exist_ok=True)
    RESULT_PATH.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result, indent=2))
    sys.exit(0 if captured >= floor else 1)


if __name__ == "__main__":
    main()
